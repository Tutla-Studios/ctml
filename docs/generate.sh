#!/usr/bin/env bash
#
# Builds the pages under docs/ from the source tree, so the reference can never drift from the code.
#
#   ./docs/generate.sh          write every generated page
#   ./docs/generate.sh --check  work out what would be written and fail if it differs from what is
#
# What is generated, and what is not:
#
#   index.md                 from the project README
#   reference/*.md           from the registries, ElementStyle, TailwindParser, Variant, TailwindColors
#   reference/java/*.md      from the javadoc of the classes in JAVA_API below
#   sidebar.json             from PAGES below, for the wiki's github sync to pick up
#
#   getting-started.md and tutorial/*.md are written by hand and never touched here. A generated page
#   carries a marker comment under its frontmatter; nothing else in docs/ is overwritten.
#
# Every registered element and property has to carry the javadoc tags the reference is built from:
#
#   elements    @ctml.group, @ctml.properties, @ctml.example
#   properties  @ctml.on, @ctml.example
#
# One missing tag stops the build and names the class, so the format cannot quietly rot.
#
# The wiki pulls this folder in through its github sync, which wants one file on its own side:
#
#   content/ctml/github.txt   containing   https://github.com/Tutla-Studios/ctml/tree/master/docs
#
# Mounted there, this folder's index.md is /ctml and sidebar.json is the project's sidebar, which is
# why every link written here starts at BASE below. Change BASE if the mount ever moves.
#
set -euo pipefail

