page_title(){ sed -n 's/^title: "\(.*\)"$/\1/p' "$OUT/$1" | head -1; }

gen_sidebar(){
    local path file title missing="" extra
    for file in $TUTORIAL_ORDER; do
        [ -f "$OUT/tutorial/$file.md" ] || missing="$missing tutorial/$file.md"
    done
    [ -n "$missing" ] && { echo "TUTORIAL_ORDER names pages that are not there:$missing" >&2; exit 1; }
    for path in "$OUT"/tutorial/*.md; do
        file="$(basename "$path" .md)"
        case " $TUTORIAL_ORDER " in *" $file "*) ;;
            *) extra="$extra tutorial/$file.md";; esac
    done
    [ -n "${extra:-}" ] && { echo "tutorial pages missing from TUTORIAL_ORDER:$extra" >&2; exit 1; }

    {
        printf '{\n'
        printf '    "github": "%s",\n' "$GITHUB"
        printf '    "modrinth": "%s",\n' "$MODRINTH"
        printf '    "website": "%s",\n' "$WEBSITE"
        printf '    "faq": {\n'
        printf '        "Do I need to write any java to make a screen?": '
        printf '"No. A .ctml file in your minecraft folder under ctml/ui is read at startup and becomes a tree. You need java only to show that tree, to put variables in it or to answer its callbacks.",\n'
        printf '        "Is a screen different from a hud?": '
        printf '"Not as a file. Nothing in the markup says which it is: building a CTMLScreen around the tree opens it as a screen, and building a CTMLHud draws the same tree over the game. A hud hears nothing from the user, so its callbacks never fire.",\n'
        printf '        "Which tailwind classes work?": '
        printf '"The ones listed in the classes reference, which is generated from the parser itself. A class nothing knows is handed back rather than quietly dropped, so your host can report a typo.",\n'
        printf '        "Why has my edit to a .ctml file not shown up?": '
        printf '"There is no hot reload yet. A changed file needs the game restarted.",\n'
        printf '        "Can I draw a ctml tree inside a gui I wrote myself?": '
        printf '"Yes. CTMLRenderer.layout gives you the boxes and CTMLRenderer.paint draws them, so a tree can go inside any screen you already have.",\n'
        printf '        "How do I check a layout without launching minecraft?": '
        printf '"The layout engine is arithmetic over a dom tree and needs no running game. The tools/headless folder in the repository lays trees out and prints the boxes."\n'
        printf '    },\n'
        printf '    "Introduction": "%s/",\n' "$BASE"
        printf '    "Getting started": "%s/getting-started",\n' "$BASE"
        printf '    "Tutorial": {\n'
        local first=1
        for file in $TUTORIAL_ORDER; do
            [ "$first" = 1 ] || printf ',\n'
            first=0
            if [ "$file" = index ]; then
                printf '        "Overview": "%s/tutorial"' "$BASE"
            else
                printf '        "%s": "%s/tutorial/%s"' "$(page_title "tutorial/$file.md")" "$BASE" "$file"
            fi
        done
        printf '\n    },\n'
        printf '    "Reference": {\n'
        printf '        "Overview": "%s/reference",\n' "$BASE"
        printf '        "Elements": "%s/reference/elements",\n' "$BASE"
        printf '        "Properties": "%s/reference/properties",\n' "$BASE"
        printf '        "Styles": "%s/reference/styles",\n' "$BASE"
        printf '        "Classes": "%s/reference/classes",\n' "$BASE"
        printf '        "Variants": "%s/reference/variants",\n' "$BASE"
        printf '        "Colours": "%s/reference/colors",\n' "$BASE"
        printf '        "Java API": {\n'
        printf '            "Overview": "%s/reference/java"' "$BASE"
        local out rel
        while IFS='|' read -r title out rel; do
            [ -n "$title" ] || continue
            printf ',\n            "%s": "%s/%s"' "$title" "$BASE" "${out%.md}"
        done < "$WORK/javalinks.tsv"
        printf '\n        }\n'
        printf '    }\n'
        printf '}\n'
    } > "$WORK/sidebar.json"

    python3 -c 'import json,sys; json.load(open(sys.argv[1]))' "$WORK/sidebar.json" \
        || { echo "the sidebar came out as invalid json" >&2; exit 1; }

    if [ "$CHECK" = 1 ]; then
        diff -q "$OUT/sidebar.json" "$WORK/sidebar.json" >/dev/null 2>&1 \
            || { echo "out of date: docs/sidebar.json" >&2; echo stale >> "$WORK/stale"; }
    else
        mv "$WORK/sidebar.json" "$OUT/sidebar.json"
        echo "  docs/sidebar.json"
    fi
}

