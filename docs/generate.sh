# The constants of one nested enum, spelled the way a class list spells them
enum_values(){
    awk -v want="$2" '
    {
        line = $0
        sub(/\/\/.*/, "", line)
        if (!body) {
            if (!match(line, "enum " want " \\{")) next
            body = 1
            line = substr(line, RSTART + RLENGTH)      # a one line enum has its values right here
        }
        gsub(/\([^)]*\)/, "", line)                     # a constant may carry arguments
        gsub(/[ \t]/, "", line)
        n = split(line, parts, ",")
        for (i = 1; i <= n; i++) {
            c = parts[i]; sub(/[;}].*/, "", c)
            if (c ~ /^[A-Z][A-Z_0-9]*$/) { v = tolower(c); gsub(/_/, "-", v); print v }
        }
        if (line ~ /[;}]/) exit
    }
    ' "$1"
}

# Every enum a registration loop walks, as "Type<tab>value", so a class whose name is built from the
# loop variable can be listed as the classes it actually registers rather than as a pattern.
loop_enums(){
    sed -n 's/.*for (\([A-Za-z]*\)\.\([A-Za-z]*\) [a-zA-Z]* : .*values().*/\1 \2/p' \
        "$SRC/ctml/style/TailwindParser.java" | sort -u \
