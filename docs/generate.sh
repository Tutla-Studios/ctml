# ---------------------------------------------------------------------------- javadoc
#
# The class-level javadoc of a file, flattened to one line per piece so the rest of the script can
# read it with grep: "B|<text>" for a line of the description, "T|<tag>|<value>" for a block tag.
# Javadoc markup becomes markdown on the way out, and a <p> becomes the blank line it stands for.
#
jdoc(){
    awk '
    function clean(s){
        while (match(s, /\{@(link|linkplain|code|literal) +[^}]*\}/)) {
            piece = substr(s, RSTART, RLENGTH)
            sub(/^\{@[a-z]+ +/, "", piece); sub(/\}$/, "", piece)
            sub(/^([A-Za-z0-9_]+\.)+/, "", piece)   # a fully qualified name reads better short
            gsub(/#/, ".", piece); sub(/^\./, "", piece)
            gsub(/[ \t]+/, " ", piece)
            s = substr(s, 1, RSTART - 1) "`" piece "`" substr(s, RSTART + RLENGTH)
        }
        gsub(/&amp;/, "\\&", s); gsub(/&lt;/, "<", s); gsub(/&gt;/, ">", s)
        gsub(/<\/?(b|i|em|code|strong)>/, "", s)
        gsub(/[ \t]+/, " ", s); gsub(/^ | $/, "", s)
        return s
    }
    function out(){
        np = 0; para = ""; nt = 0
        for (i = 0; i < kept; i++) {
            line = keep[i]
            sub(/^[ \t]*\/\*\*/, "", line)
            sub(/\*\/[ \t]*$/, "", line)
            sub(/^[ \t]*\*[ \t]?/, "", line)
            gsub(/[ \t]+$/, "", line)
            if (line ~ /^@[a-zA-Z]/) {
                if (para != "") { paras[np++] = para; para = "" }
                name = line; sub(/^@/, "", name); sub(/ .*/, "", name)
                rest = line; sub(/^@[^ ]+[ \t]*/, "", rest)
                tags[nt] = name; vals[nt] = rest; nt++
                continue
            }
            if (nt > 0) { if (line != "") vals[nt - 1] = vals[nt - 1] " " line; continue }
            gsub(/<\/?(ul|ol)>/, "", line)
            if (line ~ /^[ \t]*<li>/) {                     # a list item is a paragraph of its own
                if (para != "") { paras[np] = para; items[np++] = inlist; para = "" }
                sub(/^[ \t]*<li>[ \t]*/, "", line)
                inlist = 1
                para = line
                continue
            }
            if (line ~ /^<p>/) {
                sub(/^<p>[ \t]*/, "", line)
                if (para != "") { paras[np] = para; items[np++] = inlist; para = "" }
                inlist = 0
            }
            if (line ~ /^[ \t]*$/) {
                if (para != "") { paras[np] = para; items[np++] = inlist; para = "" }
                inlist = 0
                continue
            }
            para = (para == "" ? line : para " " line)
        }
        if (para != "") { paras[np] = para; items[np++] = inlist }
        for (i = 0; i < np; i++) {
            if (i && !(items[i] && items[i - 1])) print "B|"   # consecutive items are one list
            print "B|" (items[i] ? "- " : "") clean(paras[i])
        }
        for (i = 0; i < nt; i++) print "T|" tags[i] "|" clean(vals[i])
    }
    /^[ \t]*\/\*\*/ { blk = 1; n = 0; delete buf }
    blk { buf[n++] = $0; if ($0 ~ /\*\//) { blk = 0; for (j = 0; j < n; j++) keep[j] = buf[j]; kept = n; have = 1 } ; next }
    /^(public|final|abstract|sealed|[ \t])+(class|enum|interface|record)[ \t]/ { if (have) out(); exit }
    /[^ \t]/ { have = 0 }
    ' "$1"
}

# the description, as markdown paragraphs
jdoc_body(){ jdoc "$1" | sed -n 's/^B|//p'; }

# one block tag's value, empty where the tag is not there
jdoc_tag(){ jdoc "$1" | sed -n "s/^T|$2|//p" | head -1; }

# Every public member of a class, as "M|<signature>|<description>". A member's javadoc is the block
# that sits directly above it; one with none comes out with an empty description. Only members at the
# class's own indent are listed, so nothing inside a method body is mistaken for one.
members(){
    awk '
    function clean(s){
        while (match(s, /\{@(link|linkplain|code|literal) +[^}]*\}/)) {
            piece = substr(s, RSTART, RLENGTH)
            sub(/^\{@[a-z]+ +/, "", piece); sub(/\}$/, "", piece)
            sub(/^([A-Za-z0-9_]+\.)+/, "", piece)
            gsub(/#/, ".", piece); sub(/^\./, "", piece)
            gsub(/[ \t]+/, " ", piece)
            s = substr(s, 1, RSTART - 1) "`" piece "`" substr(s, RSTART + RLENGTH)
        }
        gsub(/&amp;/, "\\&", s); gsub(/&lt;/, "<", s); gsub(/&gt;/, ">", s)
        gsub(/<\/?(b|i|em|code|strong|ul|ol)>/, "", s); gsub(/<p>/, " ", s); gsub(/<li>/, " - ", s)
        gsub(/[ \t]+/, " ", s); gsub(/^ | $/, "", s)
        return s
    }
    # a plain block comment is skipped whole: commented out code is not a member
    cmt { if ($0 ~ /\*\//) cmt = 0; next }
    /^[ \t]*\/\*[^*]/ || /^[ \t]*\/\*$/ { if ($0 !~ /\*\//) cmt = 1; next }

    # a javadoc block, kept in case the next thing is a member
    /^[ \t]*\/\*\*/ { blk = 1; doc = "" }
    blk {
        line = $0
        sub(/^[ \t]*\/\*\*/, "", line); sub(/\*\/[ \t]*$/, "", line); sub(/^[ \t]*\*[ \t]?/, "", line)
        gsub(/[ \t]+$/, "", line)
        if (line ~ /^@/) { blk = ($0 ~ /\*\//) ? 0 : blk; pending = 1; next }   # a param or return tag adds nothing here
        if (line != "") doc = (doc == "" ? line : doc " " line)
        if ($0 ~ /\*\//) { blk = 0; pending = 1 }
        next
    }
    # a member declaration: public, at the class indent, and not a lambda or a call inside a body
    /^    public[ \t]/ {
        sig = $0
        while (sig !~ /[;{]/ && (getline more) > 0) { gsub(/^[ \t]+/, " ", more); sig = sig more }
        sub(/[ \t]*\/\/.*$/, "", sig)            # a trailing line comment is not part of the signature
        sub(/[ \t]*\{[ \t]*$/, "", sig)
        sub(/^    /, "", sig)
        gsub(/[ \t]+/, " ", sig); sub(/[ \t;]+$/, "", sig)
        # a field whose value runs on says the type and the name; the value belongs in the source
        if (length(sig) > 100 && match(sig, / = /)) sig = substr(sig, 1, RSTART - 1)
        if (length(sig) > 160) sig = substr(sig, 1, 157) "..."
        print "M|" sig "|" (pending ? clean(doc) : "")
        doc = ""; pending = 0
        next
    }
    /[^ \t]/ { if (!blk) { doc = ""; pending = 0 } }
    ' "$1"
}

# ---------------------------------------------------------------------------- shared tables
#
# Writes a page: frontmatter, the generated marker, then whatever came in on stdin. A page that is
# already there keeps its created date, so regenerating does not rewrite history, and keeps its updated
# date too for as long as nothing in it changed: only a page whose content differs gets today's.
#
emit(){
    local rel="$1" title="$2" summary="$3" path="$OUT/$1" created updated
    mkdir -p "$(dirname "$path")"
    created="$TODAY"
    updated="$TODAY"
    if [ -f "$path" ]; then
        created="$(sed -n 's/^created: "\(.*\)"$/\1/p' "$path" | head -1)"
        updated="$(sed -n 's/^updated: "\(.*\)"$/\1/p' "$path" | head -1)"
    fi
    [ -z "$created" ] && created="$TODAY"
    [ -z "$updated" ] && updated="$TODAY"
    cat > "$WORK/body"
    page(){
        printf -- '---\ntitle: "%s"\nsummary: "%s"\ncreated: "%s"\nupdated: "%s"\nisdoc: true\n---\n\n' \
            "$title" "$summary" "$created" "$1"
        printf '%s\n\n' "$MARKER"
        cat "$WORK/body"
    }
    # the same page under its old updated date: if that is what is already there, nothing changed
    page "$updated" > "$WORK/page"
    if diff -q "$path" "$WORK/page" >/dev/null 2>&1; then
        [ "$CHECK" = 1 ] || echo "  docs/$rel (unchanged)"
        return
    fi
    if [ "$CHECK" = 1 ]; then
        echo "out of date: docs/$rel" >&2
        echo stale >> "$WORK/stale"
    else
        page "$TODAY" > "$WORK/page"
        mv "$WORK/page" "$path"
        echo "  docs/$rel"
    fi
}

