# The registries, read in the order they register things, so every page lists them in that order too
build_tables(){
    style_table > "$WORK/styles.tsv"
    shorthand_table > "$WORK/shorthands.tsv"
    stylenote_table > "$WORK/stylenotes.tsv"
    variant_table > "$WORK/variants.tsv"
    loop_enums > "$WORK/enums.tsv"
    utility_table > "$WORK/utilities.raw"

    # elements, as "file<tab>tag<tab>holds children"
    : > "$WORK/elements.tsv"
    sed -n 's/^ *register(new \([A-Za-z0-9_]*\)()).*/\1/p' "$SRC/tusan/register/ElementRegistry.java" \
    | while read -r cls; do
        local file
        file="$(find "$SRC/ctml/element" -name "$cls.java" | head -1)"
        [ -n "$file" ] || { echo "no source for registered element $cls" >&2; exit 1; }
        awk -v f="$file" '
        /super\("/ { s = $0
            while (s !~ /;/ && (getline more) > 0) s = s " " more
            match(s, /super\("[^"]+"/); tag = substr(s, RSTART + 7, RLENGTH - 8)
            print f "\t" tag "\t" (s ~ /, *true *,/ ? "true" : "false")
            exit }
        ' "$file" >> "$WORK/elements.tsv"
    done

    # properties, as "file<tab>name<tab>value type"
    : > "$WORK/properties.tsv"
    sed -n 's/^ *register(new \([A-Za-z0-9_]*\)()).*/\1/p' "$SRC/tusan/register/PropertyRegistry.java" \
    | while read -r cls; do
        local file="$SRC/ctml/property/$cls.java"
        [ -f "$file" ] || { echo "no source for registered property $cls" >&2; exit 1; }
        awk -v f="$file" '
        match($0, /super\("[^"]+", *ElementPropertyType\.[A-Z]+/) {
            d = substr($0, RSTART, RLENGTH)
            match(d, /"[^"]+"/); name = substr(d, RSTART + 1, RLENGTH - 2)
            match(d, /ElementPropertyType\.[A-Z]+/); type = substr(d, RSTART + 20, RLENGTH - 20)
            print f "\t" name "\t" type
            exit }
        ' "$file" >> "$WORK/properties.tsv"
    done

    # the styles each class writes, with the four-side shorthands expanded, so the styles page can
    # look a style up and find every class that touches it
    awk -F'\t' '
    FNR == NR { parts[$1] = (($1 in parts) ? parts[$1] "," $2 : $2); next }
    {
        n = split($3, ks, ",")
        for (i = 1; i <= n; i++) {
            if (ks[i] in parts) { m = split(parts[ks[i]], side, ","); for (j = 1; j <= m; j++) print side[j] "\t" $2 }
            else print ks[i] "\t" $2
        }
    }
    ' "$WORK/shorthands.tsv" "$WORK/utilities.raw" > "$WORK/classes.tsv"

    # and the same table the other way round, for the classes page: the styles spelled out, and the
    # section of the first style a class writes, so the two pages read under the same headings
    awk -F'\t' -v tsv="$WORK/styles.tsv" -v short="$WORK/shorthands.tsv" '
    BEGIN {
        while ((getline l < tsv) > 0) {
            split(l, col, "\t")
            name[col[1]] = col[2]; section[col[1]] = col[4]
            if (!(col[4] in rank)) rank[col[4]] = ++ranks
        }
        while ((getline l < short) > 0) {
            split(l, col, "\t")
            if (col[1] in name) continue
            name[col[1]] = tolower(col[1]); gsub(/_/, "-", name[col[1]])
            section[col[1]] = section[col[2]]            # a shorthand reads where its sides read
        }
    }
    {
        out = ""; sec = ""
        n = split($3, ks, ",")
        for (i = 1; i <= n; i++) {
            if (!(ks[i] in name)) continue
            out = (out == "" ? "`" name[ks[i]] "`" : out ", `" name[ks[i]] "`")
            if (sec == "") sec = section[ks[i]]
        }
        if (sec == "") sec = "misc"
        printf "%03d\t%s\t%s\t%s\t%s\n", rank[sec], sec, $1, $2, (out == "" ? "—" : out)
    }
    ' "$WORK/utilities.raw" | sort -s -k1,1 | cut -f2- > "$WORK/utilities.tsv"
}

# A registered element or property with a tag missing would come out as a hole in the reference, so
# the build stops here instead and names it.
check_tags(){
    local file tag kids name type bad=0
    while IFS=$'\t' read -r file tag kids; do
        for t in ctml.group ctml.properties ctml.example; do
            [ -n "$(jdoc_tag "$file" "$t")" ] || { echo "<$tag> has no @$t ($file)" >&2; bad=1; }
        done
        case " $GROUP_ORDER " in *" $(jdoc_tag "$file" ctml.group) "*) ;;
            *) echo "<$tag> has an @ctml.group that is not one of: $GROUP_ORDER" >&2; bad=1;; esac
        [ -n "$(jdoc_body "$file")" ] || { echo "<$tag> has no description ($file)" >&2; bad=1; }
    done < "$WORK/elements.tsv"
    while IFS=$'\t' read -r file name type; do
        for t in ctml.on ctml.example; do
            [ -n "$(jdoc_tag "$file" "$t")" ] || { echo "$name has no @$t ($file)" >&2; bad=1; }
        done
        [ -n "$(jdoc_body "$file")" ] || { echo "$name has no description ($file)" >&2; bad=1; }
    done < "$WORK/properties.tsv"
    [ "$bad" = 0 ] || exit 1
}

main(){
    build_tables
    check_tags
    [ "$CHECK" = 1 ] && echo "checking docs/ against src/" || echo "writing docs/ from src/"
    gen_index
    gen_elements
    gen_properties
    gen_styles
    gen_classes
    gen_variants
    gen_colors
    gen_java
    gen_reference_index
    gen_sidebar
    if [ "$CHECK" = 1 ]; then
        [ -f "$WORK/stale" ] && { echo "docs/ is out of date: run ./docs/generate.sh" >&2; exit 1; }
        echo "docs/ is up to date"
    fi
}

main
