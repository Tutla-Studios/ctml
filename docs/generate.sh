# The words a length class can say instead of a number, out of the spacing parser itself
length_keywords(){
    awk '
    /private static Length spacing\(String value\)/ { body = 1; next }
    !body { next }
    /^    \}/ { exit }
    match($0, /case "[^}]*-> \{ return [^;]*;/) {
        line = substr($0, RSTART, RLENGTH)
        names = line; sub(/ *->.*/, "", names); gsub(/case */, "", names); gsub(/["  ]/, "", names)
        what = line; sub(/.*return */, "", what); sub(/;$/, "", what)
        gsub(/Length\./, "", what)
        gsub(/"/, "", names); gsub(/ /, "", names)
        if (what == "px(1)") what = "one gui pixel"
        else if (what == "AUTO") what = "whatever is left over"
        else if (what == "FULL") what = "all of the parent"
        else if (what == "viewHeight(100)") what = "the whole window height"
        else if (what == "viewWidth(100)") what = "the whole window width"
        print names "\t" what
    }
    ' "$SRC/ctml/style/TailwindParser.java"
}

