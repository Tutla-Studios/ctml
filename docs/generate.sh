# The landing page is the project README with its own heading taken off, since the wiki draws the
# title from the frontmatter. The line under the heading becomes the summary.
gen_index(){
    local title summary
    title="$(sed -n 's/^# \(.*\)$/\1/p' "$ROOT/README.md" | head -1)"
    summary="$(awk 'f && NF { print; exit } /^# /{ f = 1 }' "$ROOT/README.md" | sed 's/"/\\"/g')"
    [ -n "$title" ] || { echo "README.md has no top level heading" >&2; exit 1; }
    awk '
    !started && NR <= 4 { if (/^[-=]{3,}[ \t]*$/) { started = 1 } ; next }   # heading, tagline, rule
    !started && NF == 0 { next }
    { started = 1; if (NF || seen) { print; seen = 1 } }
    ' "$ROOT/README.md" | emit "index.md" "$title" "$summary"
}

gen_elements(){
    {
        cat <<'INTRO'
Every element ctml knows, in the order they are registered. Nothing in the markup says whether a
tree is a screen or a hud: these are the same elements either way.

An element is always written with a closing tag, except for the three that hold nothing, where one is
allowed and not needed. Every element takes every [property](/ctml/reference/properties), and the
ones listed under **Own properties** below are the ones that do something on that element in
particular.

## Where every element starts

Before a class list or a hand set style touches it, an element carries these:

INTRO
        element_defaults "$SRC/ctml/CTMLElement.java" DEFAULTS | pretty_set | sed 's/^/- `/; s/$/`/'
        cat <<'INTRO'

The styles that come down the tree are not defaults on the element, since a default on every element
would stop a parent's value ever reaching its children. They are seeded once at the root instead:

INTRO
        element_defaults "$SRC/ctml/CTMLElement.java" INHERITED_INITIAL | pretty_set | sed 's/^/- `/; s/$/`/'
        echo

        local group file tag kids own example javadoc
        for group in $GROUP_ORDER; do
            printf '## %s\n\n' "$(group_title "$group")"
            while IFS=$'\t' read -r file tag kids; do
                [ "$(jdoc_tag "$file" ctml.group)" = "$group" ] || continue
                own="$(jdoc_tag "$file" ctml.properties)"
                example="$(jdoc_tag "$file" ctml.example)"
                printf '### `<%s>`\n\n' "$tag"
                jdoc_body "$file"
                echo
                echo '| | |'
                echo '| --- | --- |'
                if [ "$kids" = true ]; then
                    printf '| Written | `<%s>` ... `</%s>` |\n' "$tag" "$tag"
                else
                    printf '| Written | `<%s>`, with `</%s>` allowed and not needed |\n' "$tag" "$tag"
                fi
                printf '| Holds children | %s |\n' "$([ "$kids" = true ] && echo yes || echo no)"
                printf '| Own properties | %s |\n' "$(echo "$own" | sed 's/\([a-z][a-z]*\)/`\1`/g; s/`none`/none/')"
                printf '| Starts with | %s |\n' "$(element_defaults "$file" | pretty_set \
                    | sed 's/^\([a-z-]*:\)/`\1/; s/^`\(.*\)$/`\1`/' | joined 'the common defaults only')"
                printf '| Java class | `%s` |\n' "$PKG.$(echo "${file#$SRC/}" | sed 's/\.java$//; s/\//./g')"
                printf '\n```html\n%s\n```\n\n' "$example"
            done < "$WORK/elements.tsv"
        done
    } | emit "reference/elements.md" "Elements" \
        "Every element CraftyTML knows, with the properties it reads, the styles it starts with and an example of each."
}

gen_properties(){
    {
        cat <<'INTRO'
A property is written on an element the way an html attribute is. Every element takes every property
here; what differs is which of them do anything, which the
[elements reference](/ctml/reference/elements) lists per element.

A boolean property needs no value: `draggable` on its own is the same as `draggable="true"`. Every
string is read through the dom context, so `${name}` anywhere in one is the variable of that name as
it stands this frame.

INTRO
        local file name type on example
