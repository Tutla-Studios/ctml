# ElementStyle, as "CONSTANT<tab>css-name<tab>value type<tab>section<tab>yes|no inherited".
# The sections are the comments the keys are grouped under in the source, so the reference reads in
# the same order and under the same headings as the code does.
style_table(){
    awk '
    BEGIN { nr = 0 }
    /^[ \t]*\/\/ / && !/key\(/ { sec = $0; sub(/^[ \t]*\/\/ /, "", sec); next }
    /INHERITED = \{/ { ih = 1; next }
    ih { if ($0 ~ /\};/) { ih = 0; next }
         line = $0; sub(/\/\/.*/, "", line); gsub(/[ \t]/, "", line)
         n = split(line, parts, ","); for (i = 1; i <= n; i++) if (parts[i] != "") inh[parts[i]] = 1
         next }
    match($0, /public static final Key<[^>]*> [A-Z_0-9]+ = key\("[^"]+"/) {
        decl = substr($0, RSTART, RLENGTH)
        match(decl, /Key<[^>]*>/); type = substr(decl, RSTART + 4, RLENGTH - 5)
        match(decl, /> [A-Z_0-9]+ =/); konst = substr(decl, RSTART + 2, RLENGTH - 4)
        match(decl, /key\("[^"]+"/); name = substr(decl, RSTART + 5, RLENGTH - 6)
        rows[nr] = konst "\t" name "\t" type "\t" sec; nr++
        next
    }
    END {
        for (i = 0; i < nr; i++) {
            split(rows[i], f, "\t")
            print rows[i] "\t" (f[1] in inh ? "yes" : "no")
        }
    }
    ' "$SRC/ctml/ElementStyle.java"
}

# CONSTANT -> css name, for turning the keys a builder or a utility names into style names
style_name(){ awk -F'\t' -v k="$1" '$1 == k { print $2; exit }' "$WORK/styles.tsv"; }

# The classes that write each style, as "CONSTANT<tab>class". A keyword is the class as written, a
# valued prefix comes out as "p-*", which is how the reference spells one that takes a value.
class_table(){
    awk '
    /^[ \t]*keyword\("/ {
        match($0, /keyword\("[^"]+"/); cls = substr($0, RSTART + 9, RLENGTH - 10)
        collect($0, cls, "keyword"); next
    }
    /^[ \t]*valued\("/ {
        match($0, /valued\("[^"]+"/); cls = substr($0, RSTART + 8, RLENGTH - 9) "-*"
        stmt = $0
        # a setter written as a block runs on, so the keys it names are below the first line
        while (stmt !~ /;[ \t]*$/ && (getline more) > 0) stmt = stmt " " more
        collect(stmt, cls, "valued"); next
    }
    function collect(stmt, cls, kind){
        seen = ""
        # a nested enum is written the same way as a key, so the name has to end where the match does
        while (match(stmt, /ElementStyle\.[A-Z][A-Za-z_0-9]*/)) {
            konst = substr(stmt, RSTART + 13, RLENGTH - 13)
            stmt = substr(stmt, RSTART + RLENGTH)
            if (konst !~ /^[A-Z][A-Z_0-9]*$/) continue      # ElementStyle.Display is a type, not a key
            if (konst == "UNSET" || konst == "KEYS") continue
            if (index(seen, "|" konst "|")) continue
            seen = seen "|" konst "|"
            print konst "\t" cls
        }
    }
    ' "$SRC/ctml/style/TailwindParser.java"
}

# The four-side shorthands, as "SHORTHAND<tab>COMPONENT", so a class that writes "padding" is listed
# under each of the four paddings it actually sets.
shorthand_table(){
    awk '
    match($0, /public static final Key<\?>\[\] [A-Z_0-9]+ = \{[^}]*\}/) {
        decl = substr($0, RSTART, RLENGTH)
        match(decl, /\] [A-Z_0-9]+ =/); konst = substr(decl, RSTART + 2, RLENGTH - 4)
        match(decl, /\{[^}]*\}/); list = substr(decl, RSTART + 1, RLENGTH - 2)
        n = split(list, parts, ",")
        for (i = 1; i <= n; i++) { gsub(/[ \t]/, "", parts[i]); if (parts[i] != "") print konst "\t" parts[i] }
    }
    ' "$SRC/ctml/ElementStyle.java"
}

# One ".set(ElementStyle.KEY, value)" as the style it writes, in the spelling a class list uses
pretty_set(){
    awk -F'\t' -v tsv="$WORK/styles.tsv" -v short="$WORK/shorthands.tsv" '
    BEGIN {
        while ((getline line < tsv) > 0) { split(line, f, "\t"); name[f[1]] = f[2] }
        # the four-side shorthands are named as themselves: "margin: 0" says more than four rows would
        while ((getline line < short) > 0) {
            split(line, f, "\t")
            if (!(f[1] in name)) { name[f[1]] = tolower(f[1]); gsub(/_/, "-", name[f[1]]) }
        }
    }
    $1 == "SEEDS" { print "and the inherited values, seeded here"; next }
    {
        konst = $1; val = $2
        if (!(konst in name)) next
        sub(/^ElementStyle\.[A-Za-z]+\./, "", val)      # ElementStyle.Display.TABLE_CELL -> TABLE_CELL
        if (val ~ /^[A-Z][A-Z_0-9]*$/) { val = tolower(val); gsub(/_/, "-", val) }
        else if (val == "Length.FULL") val = "100%"
        else if (val == "Length.ZERO") val = "0"
        else if (val ~ /^Length\.px\(/) { sub(/^Length\.px\(/, "", val); sub(/\)$/, "", val); val = val "px" }
        else if (val ~ /^0x[0-9A-Fa-f]{8}$/) val = "#" tolower(substr(val, 5))
        print name[konst] ": " val
    }
    '
}

# The styles an element starts with over the common defaults, from the builder behind its
# defaultStyle(). An element that seeds the inherited values says so instead of listing them.
element_defaults(){
    awk -v only="${2:-}" '
    /DEFAULTS\.toBuilder\(\)|ElementStyle\.builder\(\)/ { if (only == "" || index($0, only " =")) bld = 1 }
    bld && /\.setAll\(INHERITED_INITIAL\)/ { print "SEEDS\tinherited" }
    bld && match($0, /\.set\(ElementStyle\.[A-Z_0-9]+, [^)]*\)?\)/) {
        piece = substr($0, RSTART, RLENGTH)
        sub(/^\.set\(ElementStyle\./, "", piece); sub(/\)$/, "", piece)
        split(piece, f, ", ")
        print f[1] "\t" f[2]
    }
    bld && /\.build\(\);/ { bld = 0 }
    ' "$1"
}

# The variants, as "name<tab>what it asks<tab>description"
variant_table(){
    awk '
    /^public enum Variant/ { body = 1; next }
    !body { next }
    /^[ \t]*\/\*\*/ { doc = $0; sub(/^[ \t]*\/\*\*[ \t]*/, "", doc); sub(/[ \t]*\*\/[ \t]*$/, "", doc); next }
    match($0, /^[ \t]*[A-Z][A-Z_0-9]*\("[^"]+"[^)]*\)/) {
        decl = substr($0, RSTART, RLENGTH)
        match(decl, /"[^"]+"/); name = substr(decl, RSTART + 1, RLENGTH - 2)
        asks = "state"
        if (match(decl, /, *[0-9]+, *(true|false)/)) {
            px = substr(decl, RSTART, RLENGTH); gsub(/[^0-9]/, "", px)
            asks = (decl ~ /true\)/) ? "gui width at least " px : "gui width under " px
        }
        print name "\t" asks "\t" doc
        doc = ""
        next
    }
    /;[ \t]*$/ { if (body) exit }
    ' "$SRC/ctml/style/Variant.java"
}

# The palette, as "family<tab>hex<tab>hex..." and the shades it is indexed by
color_shades(){
    sed -n 's/.*int\[\] SHADES = { \(.*\) };.*/\1/p' "$SRC/ctml/style/TailwindColors.java" | tr -d ' '
}
color_table(){
    awk '
    match($0, /ramp\("[a-z]+", *(" *[0-9a-f]{6} *",? *)+\)/) {
        line = substr($0, RSTART, RLENGTH)
        match(line, /"[a-z]+"/); family = substr(line, RSTART + 1, RLENGTH - 2)
        row = family
        rest = substr(line, RSTART + RLENGTH)
        while (match(rest, /"[0-9a-f]{6}"/)) {
            row = row "\t" substr(rest, RSTART + 1, RLENGTH - 2)
            rest = substr(rest, RSTART + RLENGTH)
        }
        print row
    }
    match($0, /COLORS\.put\("[a-z]+", *0x[0-9A-Fa-f]{8}\)/) {
        line = substr($0, RSTART, RLENGTH)
        match(line, /"[a-z]+"/); family = substr(line, RSTART + 1, RLENGTH - 2)
        match(line, /0x[0-9A-Fa-f]{8}/); argb = tolower(substr(line, RSTART + 2, RLENGTH - 2))
        print "!" family "\t" argb
    }
    ' "$SRC/ctml/style/TailwindColors.java"
}

