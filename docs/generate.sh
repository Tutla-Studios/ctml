        enum_values "$file" "$type" | sed "s/^/$owner.$type\t/"
    done
}

# Every registered class, as "keyword|valued<tab>class<tab>CONST,CONST", in registration order.
#
# A registration can name its styles three ways: straight out, as ElementStyle.WIDTH; through a helper
# that holds them, as image() holds background-image; or through a helper that registers the class
# itself, as object() does. All three are followed, and a class whose name is built in a loop over an
# enum is listed once per value of that enum.
utility_table(){
    awk -v enums="$WORK/enums.tsv" '
    function konsts_of(stmt,    seen, out, konst, fn, i, n, parts) {
        seen = ""; out = ""
        # the styles named in the statement itself
        while (match(stmt, /ElementStyle\.[A-Z][A-Za-z_0-9]*/)) {
            konst = substr(stmt, RSTART + 13, RLENGTH - 13)
            stmt = substr(stmt, RSTART + RLENGTH)
            if (konst !~ /^[A-Z][A-Z_0-9]*$/ || konst == "UNSET" || konst == "KEYS") continue
            if (index(seen, "|" konst "|")) continue
            seen = seen "|" konst "|"
            out = (out == "" ? konst : out "," konst)
        }
        # and the ones held by every helper it calls
        for (fn in helper) {
            if (held[fn] == "") continue
            if (!index(call, fn "(") && !index(call, "::" fn)) continue
            n = split(held[fn], parts, ",")
            for (i = 1; i <= n; i++) {
                if (index(seen, "|" parts[i] "|")) continue
                seen = seen "|" parts[i] "|"
                out = (out == "" ? parts[i] : out "," parts[i])
            }
        }
        return out
    }
    function konsts_in(stmt,    seen, out, konst) {
        seen = ""; out = ""
        while (match(stmt, /ElementStyle\.[A-Z][A-Za-z_0-9]*/)) {
            konst = substr(stmt, RSTART + 13, RLENGTH - 13)
            stmt = substr(stmt, RSTART + RLENGTH)
            if (konst !~ /^[A-Z][A-Z_0-9]*$/ || konst == "UNSET" || konst == "KEYS") continue
            if (index(seen, "|" konst "|")) continue
            seen = seen "|" konst "|"
            out = (out == "" ? konst : out "," konst)
        }
        return out
    }
    # the whole statement a registration opens, however many lines its lambda runs to
    function bare(line) {            # parens inside a comment or a string are not the program itself
        sub(/\/\/.*/, "", line)
        gsub(/"[^"]*"/, "\"\"", line)
        return line
    }
    function statement(    s, depth, i, c, more, lines, clean) {
        s = $0; clean = bare($0); depth = 0; lines = 0
        for (;;) {
            for (i = 1; i <= length(clean); i++) {
                c = substr(clean, i, 1)
                if (c == "(") depth++
                else if (c == ")") depth--
            }
            if (depth <= 0 || ++lines > 40) break
            if ((getline more) <= 0) break
            s = s " " more
            clean = bare(more)
        }
        return s
    }
    function emit_rows(kind, cls, stmt,    n, vals, i) {
        call = stmt
        if (cls ~ /\*LOOP\*$/) {
            sub(/\*LOOP\*$/, "", cls)
            n = split(values[looptype], vals, ",")
            for (i = 1; i <= n; i++) print kind "\t" cls vals[i] "\t" konsts_of(stmt)
            return
        }
        print kind "\t" cls "\t" konsts_of(stmt)
    }

    BEGIN {
        while ((getline l < enums) > 0) {
            split(l, f, "\t")
            values[f[1]] = (f[1] in values) ? values[f[1]] "," f[2] : f[2]
        }
    }

    # pass one: what each helper holds, and which of them register a class of their own
    FNR == NR {
        if ($0 ~ /^    private static .*\(/ && $0 ~ /\{[ \t]*$/) {
            fn = $0
            sub(/\(.*/, "", fn); sub(/^.*[ \t]/, "", fn)
            # a name can be overloaded, as position() and set() are, so the bodies are added up
            # rather than replaced: between them they name every style the name can write
            if (fn ~ /^[A-Za-z_][A-Za-z_0-9]*$/) { cur = fn; helper[cur] = 1 }
            next
        }
        if (cur != "") {
            if ($0 ~ /^    \}/) { held[cur] = konsts_in(body[cur]); cur = "" ; next }  # read again each time
            body[cur] = body[cur] " " $0
            if (match($0, /keyword\("[^"]+" \+/)) {
                prefix = substr($0, RSTART + 9, RLENGTH - 12)
                registers[cur] = prefix
            }
        }
        next
    }

    # a helper that leans on another writes whatever that one writes, as position() does through
    # image(), so what each one holds is worked out once the whole file has been read
    FNR != NR && !resolved {
        resolved = 1
        for (round = 0; round < 4; round++) {
            for (leaner in helper) {
                for (leant in helper) {
                    if (leaner == leant || held[leant] == "") continue
                    if (!index(body[leaner], leant "(") && !index(body[leaner], "::" leant)) continue
                    n = split(held[leant], adds, ",")
                    for (i = 1; i <= n; i++) {
                        if (index("," held[leaner] ",", "," adds[i] ",")) continue
                        held[leaner] = (held[leaner] == "" ? adds[i] : held[leaner] "," adds[i])
                    }
                }
            }
        }
    }

    # pass two: the registrations themselves, which are all in the static initialiser. The helpers
    # under it call keyword() too, and those calls are not registrations of their own.
    /^    static \{/ { instatic = 1; next }
    /^    \}[ \t]*$/ { instatic = 0; next }
    !instatic { next }
    match($0, /for \([A-Za-z]+\.[A-Za-z]+ [a-zA-Z]+ : /) {
        looptype = substr($0, RSTART + 5, RLENGTH - 5); sub(/ .*/, "", looptype)
        next
    }
    /^        \}[ \t]*$/ { looptype = ""; next }
    /^[ \t]*keyword\("/ {
        match($0, /keyword\("[^"]+"/); cls = substr($0, RSTART + 9, RLENGTH - 10)
        if ($0 ~ /keyword\("[^"]+" \+/ && looptype != "") cls = cls "*LOOP*"
        emit_rows("keyword", cls, statement()); next
    }
    /^[ \t]*valued\("/ {
        match($0, /valued\("[^"]+"/); cls = substr($0, RSTART + 8, RLENGTH - 9)
        emit_rows("valued", cls "-*", statement()); next
    }
    # a helper that registers the class itself, as object("center", 50, 50) does
    match($0, /^        [a-z][A-Za-z]*\("[^"]+"/) {
        fn = $0; sub(/^[ \t]*/, "", fn); sub(/\(.*/, "", fn)
        if (!(fn in registers)) next
        match($0, /"[^"]+"/); name = substr($0, RSTART + 1, RLENGTH - 2)
        call = body[fn]
        print "keyword\t" registers[fn] name "\t" held[fn]
        next
    }
    ' "$SRC/ctml/style/TailwindParser.java" "$SRC/ctml/style/TailwindParser.java"
}

# The one line note a style carries in its javadoc, as "CONSTANT<tab>note". A style whose name says
# everything there is to say carries none, and gets no note here.
stylenote_table(){
    awk '
    /^[ \t]*\/\*\*/ { doc = ""; blk = 1 }
    blk {
        line = $0
        sub(/^[ \t]*\/\*\*[ \t]*/, "", line); sub(/[ \t]*\*\/[ \t]*$/, "", line)
        sub(/^[ \t]*\*[ \t]?/, "", line); gsub(/[ \t]+$/, "", line)
        if (line != "") doc = (doc == "" ? line : doc " " line)
        if ($0 ~ /\*\//) { blk = 0; ready = 1 }
        next
    }
    match($0, /= key\("[^"]+"/) {
        if (ready) {
            match($0, /> [A-Z_0-9]+ =/); konst = substr($0, RSTART + 2, RLENGTH - 4)
            print konst "\t" doc
        }
        ready = 0; next
    }
    /[^ \t]/ { ready = 0 }
    ' "$SRC/ctml/ElementStyle.java"
}

